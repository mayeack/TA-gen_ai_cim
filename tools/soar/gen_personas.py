#!/usr/bin/env python3
# encoding=utf-8
"""
gen_personas.py - regenerate the SOAR apps' generated persona modules from the
TA's ES identity lookups:

  soar_apps/medadvice_idp/medadvice_idp_consts.py
      <- lookups/medadvice_identities.csv (the simulator's personas)
       + lookups/pseudoco_identity_personas.csv (the AI Trust Lab 5 cast, which
         the simulator REFUSES: they are real Duo accounts)
  soar_apps/pseudoco_identity/pseudoco_identity_personas.py
      <- lookups/pseudoco_identity_personas.csv (trusted and victim lists the
         PseudoCo Identity connector checks before it touches Duo)

The SOAR stub app embeds the MedAdvice workshop personas so that `get user`
returns something recognisable for t.nguyen, x.collins, j.lee and friends
without contacting any directory. Keeping the table generated from the same CSV
that ES uses for entity attribution means the two never drift.

Usage:
    python3 tools/soar/gen_personas.py          # rewrite both modules
    python3 tools/soar/gen_personas.py --check  # exit 1 if either is stale

Dev-only: tools/ never ships in the TA tarball.

Copyright 2026 Splunk Inc.
Licensed under Apache License 2.0
"""

import csv
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP_ROOT = os.path.dirname(os.path.dirname(HERE))
CSV_PATH = os.path.join(APP_ROOT, 'lookups', 'medadvice_identities.csv')
OUT_PATH = os.path.join(APP_ROOT, 'soar_apps', 'medadvice_idp',
                        'medadvice_idp_consts.py')
LAB5_CSV_PATH = os.path.join(APP_ROOT, 'lookups', 'pseudoco_identity_personas.csv')
LAB5_OUT_PATH = os.path.join(APP_ROOT, 'soar_apps', 'pseudoco_identity',
                             'pseudoco_identity_personas.py')
# Lab 5 participant accounts are l5-<workshop>-<nn>: real attendee Duo logins,
# never a persona, never a victim.
PARTICIPANT_PREFIX = 'l5-'

HEADER = '''# encoding=utf-8
# medadvice_idp_consts.py - GENERATED by tools/soar/gen_personas.py from
# lookups/medadvice_identities.csv. Do not edit by hand; rerun the generator.
#
# Every persona here is a workshop fixture. The connector never contacts a
# directory and every result it returns carries "simulated": true.
#
# Copyright 2026 Splunk Inc.
# Licensed under Apache License 2.0

DIRECTORY_DEFAULT = "medadvice.example.com"
MODE_DEFAULT = "simulate"

MSG_TEST_OK = "MedAdvice IdP simulator ready (mode={mode}, directory={directory})"
MSG_MODE_UNSUPPORTED = "Unsupported mode '{mode}': only 'simulate' is implemented"
MSG_TOKEN_UNRESOLVED = ("username '{value}' looks like an unresolved token - "
                        "supply the actual username (e.g. t.nguyen)")
MSG_USERNAME_MISSING = "username is required"
MSG_DISABLED = "Account {username} disabled (simulated)"
MSG_ENABLED = "Account {username} enabled (simulated)"
MSG_SESSIONS_CLEARED = "{count} session(s) for {username} revoked (simulated)"
MSG_GET_USER = "User {username} retrieved (simulated, {known})"
MSG_LIST_SESSIONS = "{count} active session(s) for {username} (simulated)"

# Synthetic org attributes. Assigned deterministically from the username so the
# same persona always looks the same across attendees and reruns.
DEPARTMENTS = [
    "Clinical Operations", "Patient Services", "Pharmacy", "Nursing",
    "Care Coordination", "Billing", "IT - Clinical Systems", "Research",
]
CLIENT_ADDRESSES = ["76.87.129.168", "198.51.100.77", "203.0.113.42"]
SESSION_APP = "MedAdvice DemoBot"

# username -> persona. `known` distinguishes CSV personas from synthesised ones.
PERSONAS = {
'''

FOOTER = '''}}

EMAIL_INDEX = dict((p["email"].lower(), u) for u, p in PERSONAS.items())

# AI Trust Lab 5 identities (lookups/pseudoco_identity_personas.csv). They are
# real Duo accounts that only the PseudoCo Identity connector may act on, so the
# simulator refuses them - username and email forms, any account in their
# domain, and every Lab 5 participant account (l5-*) - instead of faking a
# containment that never happened.
REFUSED_USERNAMES = frozenset({refused})
REFUSED_DOMAINS = frozenset({domains})
REFUSED_PREFIXES = ("{prefix}",)
MSG_MANAGED_ELSEWHERE = ("'{{value}}' is a real Duo identity managed by PseudoCo Identity "
                         "(AI Trust Lab 5), not a MedAdvice persona - this simulator "
                         "refuses it. Run the PseudoCo Identity app instead.")
'''

LAB5_TEMPLATE = '''# encoding=utf-8
# pseudoco_identity_personas.py - GENERATED by tools/soar/gen_personas.py from
# lookups/pseudoco_identity_personas.csv. Do not edit by hand; rerun the
# generator.
#
# The AI Trust Lab 5 persona cast. The PseudoCo Identity connector only ever
# disables the asset's configured victim, and refuses outright a trusted
# persona, a participant account (l5-*) or anything outside PERSONA_DOMAINS.
#
# Copyright 2026 Splunk Inc.
# Licensed under Apache License 2.0

PERSONA_DOMAINS = frozenset({domains})
TRUSTED_PERSONAS = frozenset({trusted})
VICTIM_PERSONAS = frozenset({victims})
PARTICIPANT_PREFIX = "{prefix}"
'''


def _set_literal(values):
    return '[' + ', '.join('"{}"'.format(v) for v in sorted(values)) + ']'


def lab5_rows():
    with io.open(LAB5_CSV_PATH, encoding='utf-8', newline='') as handle:
        rows = list(csv.DictReader(handle))
    out = []
    for row in rows:
        user, _, email = row['identity'].strip().lower().partition('|')
        if user.startswith(PARTICIPANT_PREFIX):
            raise ValueError('participant account {} must not be a persona'.format(user))
        out.append({'username': user, 'email': (email or row['email']).strip().lower(),
                    'category': row['category'].strip()})
    return out


def lab5_lists():
    rows = lab5_rows()
    domains = sorted(set(r['email'].split('@', 1)[1] for r in rows if '@' in r['email']))
    return {
        'refused': _set_literal(r['username'] for r in rows),
        'trusted': _set_literal(r['username'] for r in rows if r['category'] == 'lab5_trusted'),
        'victims': _set_literal(r['username'] for r in rows if r['category'] == 'lab5_victim'),
        'domains': _set_literal(domains),
        'prefix': PARTICIPANT_PREFIX,
    }


def render():
    rows = []
    with io.open(CSV_PATH, encoding='utf-8', newline='') as handle:
        for row in csv.DictReader(handle):
            rows.append(row)
    rows.sort(key=lambda r: r['identity'])
    out = [HEADER]
    for row in rows:
        username = row['identity'].strip().lower()
        first = row['first'].strip()
        last = row['last'].strip()
        display = '{} {}'.format(first if len(first) > 1 else first + '.', last)
        out.append(
            '    "{u}": {{"username": "{u}", "email": "{e}", "display_name": "{d}",\n'
            '        "first_name": "{f}", "last_name": "{l}", "business_unit": "{b}",\n'
            '        "category": "{c}", "watchlist": {w}, "priority": "{p}", "known": True}},\n'
            .format(u=username, e=row['email'].strip().lower(), d=display, f=first,
                    l=last, b=row['bunit'].strip(), c=row['category'].strip(),
                    w='True' if row['watchlist'].strip().lower() == 'true' else 'False',
                    p=row['priority'].strip()))
    out.append(FOOTER.format(**lab5_lists()))
    return ''.join(out)


def render_lab5():
    return LAB5_TEMPLATE.format(**lab5_lists())


def main(argv):
    outputs = ((OUT_PATH, render()), (LAB5_OUT_PATH, render_lab5()))
    if '--check' in argv:
        stale = 0
        for path, text in outputs:
            current = ''
            if os.path.exists(path):
                with io.open(path, encoding='utf-8') as handle:
                    current = handle.read()
            if current != text:
                print('STALE: {} does not match the lookups; rerun gen_personas.py'.format(path),
                      file=sys.stderr)
                stale = 1
            else:
                print('OK: {} is in sync'.format(path))
        return stale
    for path, text in outputs:
        with io.open(path, 'w', encoding='utf-8') as handle:
            handle.write(text)
        print('Wrote {}'.format(path))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
